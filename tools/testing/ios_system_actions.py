"""Loopback phase bridge для отдельного iOS acceptance log; без app session/draft."""

import argparse
import hashlib
from http.server import BaseHTTPRequestHandler, HTTPServer
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import subprocess


BUNDLE_ID = "com.example.appStackcard"
MAX_PDF_BYTES = 20 * 1024 * 1024
UUID = r"[0-9A-Fa-f]{8}(?:-[0-9A-Fa-f]{4}){3}-[0-9A-Fa-f]{12}"


def parse_harness_log(text):
    marker = None
    expected_path = None
    generated = None
    saved = cancelled = False
    media = None
    notification = None
    for raw in text.splitlines():
        line = re.sub(r"\x1b\[[0-?]*[ -/]*[@-~]", "", raw).strip()
        line = re.sub(r"^(?:flutter: |I/flutter \(\s*\d+\): )", "", line)
        if line == "STACKCARD_PDF_ACCEPTANCE:GENERATING":
            marker, expected_path, generated, media, notification = None, None, None, None, None
            saved = cancelled = False
        match = re.fullmatch(r"STACKCARD_PDF_ACCEPTANCE:EXPECTED_PATH=(.+)", line)
        if match:
            expected_path = match[1]
        match = re.fullmatch(r"STACKCARD_PDF_ACCEPTANCE:GENERATED bytes=([0-9]+) pages=([0-9]+)", line)
        if match:
            generated = (int(match[1]), int(match[2]))
        if line == "STACKCARD_PDF_ACCEPTANCE:SAVE_READY":
            marker = {"kind": "pdf", "stage": "SAVE_READY"}
            media = notification = None
        elif line == "STACKCARD_PDF_ACCEPTANCE:SAVE_PASS":
            saved = True
        elif line == "STACKCARD_PDF_ACCEPTANCE:CANCEL_READY" and saved:
            marker = {"kind": "pdf", "stage": "CANCEL_READY"}
            media = notification = None
        elif line == "STACKCARD_PDF_ACCEPTANCE:CANCEL_PASS" and saved:
            cancelled = True
        elif line == "STACKCARD_PDF_ACCEPTANCE:ALL_PASS" and saved and cancelled:
            marker = {"kind": "pdf", "stage": "ALL_PASS"}
        match = re.fullmatch(
            r"STACKCARD_MEDIA_ACCEPTANCE:(READY|PASS) source=(camera|gallery) "
            r"expected=(cancel|permissionDenied|unavailable|selected)", line)
        if match:
            selection = (match[2], match[3])
            if match[1] == "READY":
                media = selection
                notification = None
            if match[1] == "READY" or media == selection:
                marker = {"kind": "media", "stage": match[1],
                          "source": match[2], "outcome": match[3]}
        match = re.fullmatch(
            r"STACKCARD_NOTIFICATION_ACCEPTANCE:(READY|PASS) "
            r"expected=(denied|authorized)", line)
        if match:
            if match[1] == "READY":
                notification = match[2]
                media = None
            if match[1] == "READY" or notification == match[2]:
                marker = {"kind": "notification", "stage": match[1],
                          "permission": match[2]}
    return marker, expected_path, generated


def expected_pdf(container, logged_path, generated):
    """Читает только известный temporary fixture внутри указанного target container."""
    if not generated or not 5 <= generated[0] <= MAX_PDF_BYTES or generated[1] < 2:
        raise ValueError("invalid_generated_metadata")
    if not logged_path or any(ord(char) < 32 for char in logged_path):
        raise ValueError("invalid_expected_path")
    if any(part in (".", "..") for part in logged_path.split("/")):
        raise ValueError("invalid_expected_path")
    raw = PurePosixPath(logged_path)
    if not raw.is_absolute() or raw.name != "expected.pdf":
        raise ValueError("invalid_expected_path")
    if not re.fullmatch(r"stackcard-pdf-acceptance-[A-Za-z0-9_-]{1,80}", raw.parent.name):
        raise ValueError("invalid_fixture_directory")
    if raw.parent.parent.name != "tmp":
        raise ValueError("invalid_fixture_directory")
    container = container.resolve(strict=True)
    allowed = {str(container), f"/var/mobile/Containers/Data/Application/{container.name}",
               f"/private/var/mobile/Containers/Data/Application/{container.name}"}
    if str(raw.parents[2]) not in allowed:
        try:
            same_host_container = Path(raw.parents[2]).resolve(strict=True) == container
        except OSError:
            same_host_container = False
        if not same_host_container:
            raise ValueError("foreign_app_container")
    candidate = container / "tmp" / raw.parent.name / "expected.pdf"
    if any(path.is_symlink() for path in (candidate, candidate.parent, candidate.parent.parent)):
        raise ValueError("symlink_fixture")
    resolved = candidate.resolve(strict=True)
    if not resolved.is_relative_to(container / "tmp") or not stat.S_ISREG(resolved.stat().st_mode):
        raise ValueError("invalid_fixture_file")
    if resolved.stat().st_size != generated[0]:
        raise ValueError("generated_size_mismatch")
    data = resolved.read_bytes()
    if len(data) != generated[0] or not data.startswith(b"%PDF-"):
        raise ValueError("invalid_pdf_fixture")
    return data


class PhaseBridge:
    def __init__(self, log, output, device, container):
        self.log, self.output, self.device, self.container = log, output, device, container
        self.copy_path = output.with_suffix(".expected.pdf")
        self.expected_path = None
        self.expected = None
        self.identity = (log.stat().st_dev, log.stat().st_ino)
        self.size = log.stat().st_size

    def status(self):
        info = self.log.stat()
        if self.log.is_symlink() or (info.st_dev, info.st_ino) != self.identity or info.st_size < self.size:
            raise ValueError("harness_log_replaced_or_truncated")
        self.size = info.st_size
        with self.log.open("rb") as stream:
            stream.seek(max(0, info.st_size - 1024 * 1024))
            text = stream.read(1024 * 1024).decode("utf-8", errors="replace")
        marker, path, generated = parse_harness_log(text)
        result = dict(marker or {"kind": "waiting", "stage": "WAITING"})
        if marker and marker["kind"] == "pdf":
            if self.expected_path is not None and self.expected_path != path:
                raise ValueError("new_harness_requires_new_output")
            if self.expected is None:
                data = expected_pdf(self.container, path, generated)
                with self.copy_path.open("xb") as stream:
                    os.chmod(self.copy_path, 0o600)
                    stream.write(data)
                    stream.flush()
                    os.fsync(stream.fileno())
                self.expected_path = path
                self.expected = {"copy": self.copy_path.name, "bytes": len(data),
                                 "sha256": hashlib.sha256(data).hexdigest()}
            result["sourceVerified"] = True
        self.write_summary(result)
        return result

    def write_summary(self, marker, error=None):
        summary = {"scope": "iOS Simulator synthetic native picker bridge", "device": self.device,
                   "marker": marker, "expected": self.expected,
                   "acceptance": "Flutter exit0 and native UI results required; PDF export byte comparison separate"}
        if error:
            summary["error"] = error
        self.output.write_text(json.dumps(summary, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--log", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--device", required=True)
    args = parser.parse_args()
    if not re.fullmatch(UUID, args.device):
        parser.error("device must be an explicit iOS Simulator UUID")
    if args.log.is_symlink() or not args.log.is_file():
        parser.error("log must be the existing regular opt-in harness log")
    output = args.output.resolve()
    if output.exists() or output.with_suffix(".expected.pdf").exists() or output == args.log.resolve():
        parser.error("output and expected copy must be new files outside the harness log")
    container = Path(subprocess.check_output(
        ["xcrun", "simctl", "get_app_container", args.device, BUNDLE_ID, "data"],
        text=True, timeout=15).strip()).resolve(strict=True)
    layout = container.parts
    suffix = ("data", "Containers", "Data", "Application", container.name)
    if (not re.fullmatch(UUID, container.name) or tuple(layout[-5:]) != suffix
            or len(layout) < 7 or layout[-7] != "Devices" or layout[-6].lower() != args.device.lower()):
        parser.error("unexpected target Simulator app container")
    if output.is_relative_to(container):
        parser.error("output must be outside the application container")
    output.parent.mkdir(parents=True, exist_ok=True)
    bridge = PhaseBridge(args.log.resolve(), output, args.device, container)

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_args):
            pass

        def do_GET(self):
            if (self.client_address[0] != "127.0.0.1" or self.path != "/status"
                    or self.headers.get("Host") != "127.0.0.1:3812"):
                self.send_error(404)
                return
            try:
                data, code = bridge.status(), 200
            except (ValueError, OSError) as error:
                reason = str(error) if isinstance(error, ValueError) else "fixture_or_log_unavailable"
                data, code = {"kind": "error", "stage": "UNAVAILABLE"}, 503
                bridge.write_summary(data, reason)
            body = json.dumps(data).encode()
            self.send_response(code)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)

    server = HTTPServer(("127.0.0.1", 3812), Handler)
    bridge.write_summary({"kind": "waiting", "stage": "WAITING"})
    print("IOS_SYSTEM ready 127.0.0.1:3812; only strict harness markers are served", flush=True)
    try:
        server.serve_forever()
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
