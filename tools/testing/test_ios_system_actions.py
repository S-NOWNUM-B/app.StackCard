import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

from ios_system_actions import PhaseBridge, expected_pdf, main, parse_harness_log


class IOSSystemActionsTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.container = self.root / '11111111-2222-3333-4444-555555555555'
        self.fixture = self.container / 'tmp/stackcard-pdf-acceptance-fixture/expected.pdf'
        self.fixture.parent.mkdir(parents=True)
        self.data = b'%PDF-1.7\n' + b'fixture' * 30
        self.fixture.write_bytes(self.data)
        self.log = self.root / 'harness.log'
        self.output = self.root / 'summary.json'
        self.text = '\n'.join([
            'flutter: STACKCARD_PDF_ACCEPTANCE:GENERATING',
            f'flutter: STACKCARD_PDF_ACCEPTANCE:EXPECTED_PATH={self.fixture}',
            f'flutter: STACKCARD_PDF_ACCEPTANCE:GENERATED bytes={len(self.data)} pages=3',
            'flutter: STACKCARD_PDF_ACCEPTANCE:SAVE_READY',
        ]) + '\n'
        self.log.write_text(self.text)

    def test_only_strict_markers_and_real_save_cancel_ack_sequence_are_accepted(self):
        marker, path, generated = parse_harness_log(self.text)
        self.assertEqual(marker, {'kind': 'pdf', 'stage': 'SAVE_READY'})
        self.assertEqual(path, str(self.fixture))
        self.assertEqual(generated, (len(self.data), 3))
        for suffix in ['prefix STACKCARD_PDF_ACCEPTANCE:ALL_PASS',
                       'STACKCARD_PDF_ACCEPTANCE:CANCEL_READY extra',
                       'STACKCARD_PDF_ACCEPTANCE:ALL_PASS']:
            self.assertEqual(parse_harness_log(self.text + suffix)[0], marker)
        complete = self.text + '\n'.join([
            'flutter: STACKCARD_PDF_ACCEPTANCE:SAVE_PASS',
            'flutter: STACKCARD_PDF_ACCEPTANCE:CANCEL_READY',
            'flutter: STACKCARD_PDF_ACCEPTANCE:CANCEL_PASS',
            'flutter: STACKCARD_PDF_ACCEPTANCE:ALL_PASS',
        ])
        self.assertEqual(parse_harness_log(complete)[0], {'kind': 'pdf', 'stage': 'ALL_PASS'})
        self.assertIsNone(parse_harness_log(complete + '\nflutter: STACKCARD_PDF_ACCEPTANCE:GENERATING')[0])

    def test_media_pass_requires_matching_ready_source_and_outcome(self):
        ready = 'flutter: STACKCARD_MEDIA_ACCEPTANCE:READY source=gallery expected=cancel\n'
        expected = {'kind': 'media', 'stage': 'READY', 'source': 'gallery', 'outcome': 'cancel'}
        self.assertEqual(parse_harness_log(ready)[0], expected)
        for invalid in ['PASS source=camera expected=cancel', 'PASS source=gallery expected=selected',
                        'PASS source=gallery expected=cancel extra']:
            self.assertEqual(parse_harness_log(ready + 'flutter: STACKCARD_MEDIA_ACCEPTANCE:' + invalid)[0], expected)
        self.assertEqual(parse_harness_log(ready + 'flutter: STACKCARD_MEDIA_ACCEPTANCE:PASS source=gallery expected=cancel')[0],
                         {**expected, 'stage': 'PASS'})

    def test_notification_pass_requires_matching_ready_and_exact_permission(self):
        for permission in ['denied', 'authorized']:
            with self.subTest(permission=permission):
                ready = f'flutter: STACKCARD_NOTIFICATION_ACCEPTANCE:READY expected={permission}\n'
                passed = f'flutter: STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected={permission}'
                expected = {'kind': 'notification', 'stage': 'READY', 'permission': permission}
                self.assertIsNone(parse_harness_log(passed)[0])
                self.assertEqual(parse_harness_log(ready)[0], expected)
                self.assertEqual(parse_harness_log(ready + passed)[0], {**expected, 'stage': 'PASS'})
                for invalid in [
                        'prefix ' + passed, passed + ' extra',
                        'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=notDetermined',
                        'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=provisional',
                        'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=AUTHORIZED',
                        'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=' + ('authorized' if permission == 'denied' else 'denied')]:
                    self.assertEqual(parse_harness_log(ready + invalid)[0], expected)

    def test_notification_new_ready_invalidates_previous_permission_episode(self):
        text = ('STACKCARD_NOTIFICATION_ACCEPTANCE:READY expected=denied\n'
                'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=denied\n'
                'STACKCARD_NOTIFICATION_ACCEPTANCE:READY expected=authorized\n'
                'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=denied\n')
        self.assertEqual(parse_harness_log(text)[0],
                         {'kind': 'notification', 'stage': 'READY', 'permission': 'authorized'})
        self.assertIsNone(parse_harness_log(text + 'STACKCARD_PDF_ACCEPTANCE:GENERATING\n'
                                          'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=authorized')[0])
        media = text + 'STACKCARD_MEDIA_ACCEPTANCE:READY source=gallery expected=cancel\n'
        self.assertEqual(parse_harness_log(media + 'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=authorized')[0],
                         {'kind': 'media', 'stage': 'READY', 'source': 'gallery', 'outcome': 'cancel'})
        pdf = text + 'STACKCARD_PDF_ACCEPTANCE:SAVE_READY\n'
        self.assertEqual(parse_harness_log(pdf + 'STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=authorized')[0],
                         {'kind': 'pdf', 'stage': 'SAVE_READY'})

    def test_notification_bridge_does_not_read_or_copy_pdf_fixtures(self):
        self.log.write_text('STACKCARD_NOTIFICATION_ACCEPTANCE:READY expected=authorized\n')
        bridge = PhaseBridge(self.log, self.output, 'simulator', self.container)
        with mock.patch('ios_system_actions.expected_pdf') as pdf:
            self.assertEqual(bridge.status(),
                             {'kind': 'notification', 'stage': 'READY', 'permission': 'authorized'})
            with self.log.open('a') as stream:
                stream.write('STACKCARD_NOTIFICATION_ACCEPTANCE:PASS expected=authorized\n')
            self.assertEqual(bridge.status()['stage'], 'PASS')
            pdf.assert_not_called()
        self.assertFalse(self.output.with_suffix('.expected.pdf').exists())
        self.assertIsNone(json.loads(self.output.read_text())['expected'])

    def test_expected_source_accepts_only_own_temporary_fixture_with_matching_size(self):
        alias = f'/var/mobile/Containers/Data/Application/{self.container.name}/tmp/{self.fixture.parent.name}/expected.pdf'
        self.assertEqual(expected_pdf(self.container, alias, (len(self.data), 3)), self.data)
        for path, metadata in [
                (str(self.fixture).replace(self.container.name, 'foreign-app'), (len(self.data), 3)),
                (str(self.fixture).replace('/tmp/', '/Documents/'), (len(self.data), 3)),
                (str(self.fixture).replace('/tmp/', '/tmp/../tmp/'), (len(self.data), 3)),
                (str(self.fixture).replace('expected.pdf', 'draft.json'), (len(self.data), 3)),
                (str(self.fixture), (len(self.data) + 1, 3)),
                (str(self.fixture), (len(self.data), 1))]:
            with self.subTest(path=path, metadata=metadata), self.assertRaises(ValueError):
                expected_pdf(self.container, path, metadata)
        self.fixture.write_bytes(b'not-pdf')
        with self.assertRaises(ValueError):
            expected_pdf(self.container, str(self.fixture), (7, 3))

    def test_symlink_fixture_never_reads_outside_app_temporary_directory(self):
        outside = self.root / 'ordinary.pdf'
        outside.write_bytes(self.data)
        self.fixture.unlink()
        self.fixture.symlink_to(outside)
        with self.assertRaisesRegex(ValueError, 'symlink'):
            expected_pdf(self.container, str(self.fixture), (len(self.data), 3))
        self.assertEqual(outside.read_bytes(), self.data)

    def test_bridge_copies_before_verification_and_preserves_proof_after_fixture_cleanup(self):
        bridge = PhaseBridge(self.log, self.output, 'simulator', self.container)
        self.assertEqual(bridge.status(), {'kind': 'pdf', 'stage': 'SAVE_READY', 'sourceVerified': True})
        copy = self.output.with_suffix('.expected.pdf')
        self.assertEqual(copy.read_bytes(), self.data)
        self.assertEqual(copy.stat().st_mode & 0o777, 0o600)
        self.fixture.unlink()
        with self.log.open('a') as stream:
            stream.write('flutter: STACKCARD_PDF_ACCEPTANCE:SAVE_PASS\n'
                         'flutter: STACKCARD_PDF_ACCEPTANCE:CANCEL_READY\n')
        self.assertEqual(bridge.status()['stage'], 'CANCEL_READY')
        summary = self.output.read_text()
        self.assertNotIn(str(self.root), summary)
        self.assertEqual(json.loads(summary)['expected']['bytes'], len(self.data))

    def test_bridge_rejects_reused_log_or_new_episode_without_overwriting_saved_copy(self):
        bridge = PhaseBridge(self.log, self.output, 'simulator', self.container)
        bridge.status()
        self.log.write_text('flutter: STACKCARD_PDF_ACCEPTANCE:GENERATING\n')
        with self.assertRaisesRegex(ValueError, 'truncated'):
            bridge.status()
        self.assertEqual(self.output.with_suffix('.expected.pdf').read_bytes(), self.data)

    def test_invalid_cli_device_rejected_before_any_simulator_lookup(self):
        with mock.patch.object(sys, 'argv', ['ios_system_actions.py', '--device', 'ordinary-device',
                                            '--log', str(self.log), '--output', str(self.output)]), \
                mock.patch('ios_system_actions.subprocess.check_output') as sdk:
            with self.assertRaises(SystemExit) as failure:
                main()
            self.assertEqual(failure.exception.code, 2)
            sdk.assert_not_called()
            self.assertFalse(self.output.exists())

    def test_foreign_cli_container_rejected_before_binding_or_reading_fixture(self):
        with mock.patch.object(sys, 'argv', ['ios_system_actions.py',
                                            '--device', 'AAAAAAAA-BBBB-CCCC-DDDD-EEEEEEEEEEEE',
                                            '--log', str(self.log), '--output', str(self.output)]), \
                mock.patch('ios_system_actions.subprocess.check_output', return_value=str(self.container)), \
                mock.patch('ios_system_actions.HTTPServer') as server:
            with self.assertRaises(SystemExit) as failure:
                main()
            self.assertEqual(failure.exception.code, 2)
            server.assert_not_called()
            self.assertFalse(self.output.exists())


if __name__ == '__main__':
    unittest.main()
