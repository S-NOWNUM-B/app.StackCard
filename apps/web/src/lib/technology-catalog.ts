// Ключ сравнения как в mobile: регистр, пробелы, точки и дефисы не важны («Next.js» = «nextjs»).
const key = (value: string) => value.toLowerCase().replace(/[^a-z0-9+#а-яё]/g, '');
const index = new Map<string, TechnologyInfo>();
// Обход с конца: при совпадении синонимов выигрывает более популярная запись, как в mobile.
for (const info of [...technologyCatalog].reverse()) {
  for (const alias of info.aliases) index.set(key(alias), info);
  index.set(key(info.title), info);
}

// Известная технология по названию или синониму; иначе null.
export function findTechnology(label: string): TechnologyInfo | null {
  const k = key(label);
  return (k && index.get(k)) || null;
}

// Подсказки: начало названия, начало синонима, вхождение в название, вхождение в синоним.
export function technologySuggestions(
  query: string,
  exclude: Iterable<string> = [],
  limit = 6,
): TechnologyInfo[] {
  const q = key(query);
  if (!q) return [];
  const excluded = new Set(Array.from(exclude, key));
  const scored: [number, number, TechnologyInfo][] = [];
  technologyCatalog.forEach((info, position) => {
    if (excluded.has(key(info.title))) return;
    const title = key(info.title),
      aliases = info.aliases.map(key);
    const score = title.startsWith(q)
      ? 0
      : aliases.some((alias) => alias.startsWith(q))
        ? 1
        : title.includes(q)
          ? 2
          : aliases.some((alias) => alias.includes(q))
            ? 3
            : null;
    if (score !== null) scored.push([score, position, info]);
  });
  return scored
    .sort((a, b) => a[0] - b[0] || a[1] - b[1])
    .slice(0, limit)
    .map((item) => item[2]);
}
