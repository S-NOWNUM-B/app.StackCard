import 'dart:convert';
import 'dart:io';

import 'package:app_stackcard/features/portfolio_draft/data/asset_portfolio_pdf_generator.dart';
import 'package:app_stackcard/features/portfolio_draft/portfolio_draft.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:image/image.dart' as image;
import 'package:integration_test/integration_test.dart';

/// Opt-in проверка настоящего системного file picker. Оператор сохраняет первый
/// файл и отменяет второй. Auth, Firebase, Hive и обычный draft не открываются.
void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  const enabled = bool.fromEnvironment('RUN_PDF_ACCEPTANCE');

  testWidgets(
    'native PDF picker writes the generated Cyrillic document and reports cancellation',
    (tester) async {
      expect(Platform.isAndroid || Platform.isIOS, isTrue);
      final semantics = tester.ensureSemantics();
      try {
        await _stage(tester, 'GENERATING');
        final avatar = image.Image(width: 512, height: 512);
        image.fill(avatar, color: image.ColorRgb8(196, 209, 220));
        const ids = [
          'folder',
          'file-text',
          'panels-top-left',
          'home',
          'image',
          'camera',
          'user-round',
        ];
        final content = PortfolioContent(
          profile: const PortfolioProfile(
            name: 'Анна Ёлкина',
            headline: 'Проверка настоящего PDF',
            bio: 'Одноразовый тестовый документ. Пользовательские данные не используются.',
            locationText: 'Алматы, Казахстан',
            publishLocation: true,
            avatarPath: 'accounts/disposable-pdf/media/0123456789abcdef0123456789abcdef.jpg',
          ),
          projects: [
            for (final id in ids)
              PortfolioProject(
                id: id,
                iconId: id,
                title: 'Проект $id',
                description: id == 'folder'
                    ? List.filled(
                        40,
                        'Длинное описание проекта на русском языке: перенос текста не теряет содержание. ',
                      ).join()
                    : 'Описание проекта.',
                technologies: const ['Flutter', 'TypeScript'],
                liveUrl: 'https://example.org/$id',
                repositoryUrl: 'https://github.com/example/$id',
              ),
          ],
          links: const [
            SocialLink(
              id: 'email',
              label: 'Почта',
              url: 'mailto:fixture@example.org',
              kind: SocialLinkKind.email,
              publishAllowed: true,
            ),
          ],
        );
        expect(validatePortfolioContent(content), isEmpty);
        final bytes = await tester.runAsync(
          () => AssetPortfolioPdfGenerator().generate(
            content,
            avatarBytes: image.encodeJpg(avatar),
          ),
        );
        expect(bytes, isNotNull);
        expect(isPortfolioPdfBytes(bytes!), isTrue);
        final source = latin1.decode(bytes);
        final pages = RegExp(r'/Type\s*/Page\b').allMatches(source).length;
        expect(pages, greaterThan(1));
        expect(source, contains('/ToUnicode'));
        expect(source, contains('mailto:fixture@example.org'));

        // Пока открыт первый/второй picker, оператор может забрать оригинал через
        // adb run-as и сравнить hash с файлом Downloads. После теста он удаляется.
        final directory = await Directory.systemTemp.createTemp(
          'stackcard-pdf-acceptance-',
        );
        final expected = File('${directory.path}/expected.pdf');
        try {
          await expected.writeAsBytes(bytes, flush: true);
          debugPrint('STACKCARD_PDF_ACCEPTANCE:EXPECTED_PATH=${expected.path}');
          debugPrint(
            'STACKCARD_PDF_ACCEPTANCE:GENERATED bytes=${bytes.length} pages=$pages',
          );
          const actions = NativeDocumentLinkActions();
          await _stage(tester, 'SAVE_READY');
          final saved = await tester.runAsync(
            () => actions
                .savePdf(bytes, filename: 'stackcard-native-acceptance.pdf')
                .timeout(const Duration(minutes: 5)),
          );
          expect(
            saved,
            isTrue,
            reason: 'Подтверждение приходит после записи PDF.',
          );
          await _stage(tester, 'SAVE_PASS');
          await _stage(tester, 'CANCEL_READY');
          final cancelled = await tester.runAsync(
            () => actions
                .savePdf(bytes, filename: 'stackcard-native-cancel.pdf')
                .timeout(const Duration(minutes: 5)),
          );
          expect(
            cancelled,
            isFalse,
            reason: 'Отмена не считается сохранением.',
          );
          await _stage(tester, 'CANCEL_PASS');
          expect(tester.takeException(), isNull);
          await _stage(tester, 'ALL_PASS');
        } finally {
          if (await directory.exists()) await directory.delete(recursive: true);
        }
      } finally {
        semantics.dispose();
      }
    },
    skip: !enabled,
    timeout: const Timeout(Duration(minutes: 11)),
  );
}

Future<void> _stage(WidgetTester tester, String marker) async {
  await tester.pumpWidget(
    MaterialApp(
      home: Scaffold(
        appBar: AppBar(title: const Text('StackCard PDF acceptance')),
        body: Center(
          child: Padding(
            padding: const EdgeInsets.all(24),
            child: Text(
              'STACKCARD_PDF_ACCEPTANCE:$marker',
              key: const Key('pdf.acceptance.status'),
              textAlign: TextAlign.center,
            ),
          ),
        ),
      ),
    ),
  );
  await tester.pumpAndSettle();
  debugPrint('STACKCARD_PDF_ACCEPTANCE:$marker');
}
